const { contextBridge, ipcRenderer } = require('electron');

async function invoke(channel, value) {
  try { return await ipcRenderer.invoke(channel, value); }
  catch (error) { throw new Error(error.message.replace(/^Error invoking remote method '[^']+': (?:Error: )?/u, '')); }
}

contextBridge.exposeInMainWorld('petApp', {
  info: () => invoke('pet:info'),
  desktopState: () => invoke('desktop:status'),
  setGameMode: (enabled) => invoke('desktop:game-mode', enabled),
  setPetHidden: (hidden) => invoke('desktop:hidden', hidden),
  onDesktopState: (callback) => ipcRenderer.on('desktop:state', (_event, state) => callback(state)),
  updateStatus: () => invoke('updates:status'),
  checkUpdates: (options) => invoke('updates:check', options),
  downloadUpdate: () => invoke('updates:download'),
  installUpdate: () => invoke('updates:install'),
  cancelUpdate: () => ipcRenderer.send('updates:cancel'),
  openReleases: () => invoke('updates:page'),
  showUpdateFile: () => invoke('updates:show-file'),
  openDeepSeekHelp: (page) => invoke('help:deepseek', page),
  onUpdate: (callback) => ipcRenderer.on('updates:state', (_event, state) => callback(state)),
  onUpdateFocus: (callback) => ipcRenderer.on('updates:focus', () => callback()),
  onSettingsPage: (callback) => ipcRenderer.on('settings:page', (_event, page) => callback(page)),
  interactions: () => invoke('interaction:catalog'),
  executeInteraction: (command) => invoke('interaction:execute', command),
  stickers: () => invoke('companion:stickers'),
  editMedia: (command) => invoke('media:edit', command),
  importStickers: () => invoke('companion:sticker-import'),
  openStickerFolder: () => invoke('companion:sticker-folder'),
  showSticker: (id) => invoke('interaction:execute', { type: 'showSticker', id }),
  hideSticker: () => invoke('interaction:execute', { type: 'hideSticker' }),
  preferences: () => invoke('companion:preferences'),
  savePreferences: (value) => invoke('companion:save', value),
  previewVolume: (value) => ipcRenderer.send('companion:preview-volume', value),
  onVolume: (callback) => ipcRenderer.on('companion:volume', (_event, value) => callback(value)),
  action: (id) => invoke('companion:action', id),
  voices: () => invoke('companion:voices'),
  playVoice: (id) => invoke('companion:voice', id),
  openVoiceFolder: () => invoke('companion:voice-folder'),
  stopVoice: () => invoke('interaction:execute', { type: 'stopVoice' }),
  musicStatus: () => invoke('music:status'),
  importMusic: () => invoke('music:import'),
  importVoices: () => invoke('companion:voice-import'),
  normalizeAudio: kind => invoke('audio:normalize', kind),
  onAudioProgress: callback => ipcRenderer.on('audio:progress', (_event, value) => callback(value)),
  onMusicState: callback => ipcRenderer.on('music:state', (_event, state) => callback(state)),
  onMusicControl: callback => ipcRenderer.on('pet:music-control', (_event, command) => callback(command)),
  voiceStatus: (status) => ipcRenderer.send('companion:voice-status', status),
  readSettings: () => invoke('settings:read'),
  saveSettings: (value) => invoke('settings:save', value),
  clearKey: () => invoke('settings:clear-key'),
  history: () => invoke('chat:history'),
  memories: () => invoke('chat:memories'),
  remember: (text) => invoke('chat:remember', text),
  forget: (id) => invoke('chat:forget', id),
  clearHistory: () => invoke('chat:clear'),
  sendMessage: (text) => invoke('chat:send', text),
  cancelMessage: () => ipcRenderer.send('chat:cancel'),
  speechLanguages: () => invoke('speech:languages'),
  startSpeech: (options) => invoke('speech:start', options),
  configureSpeech: (autoSend) => invoke('speech:configure', autoSend),
  stopSpeech: () => invoke('speech:stop'),
  speechStatus: () => invoke('speech:status'),
  pendingSpeech: () => invoke('speech:pending'),
  onSpeech: (callback) => ipcRenderer.on('speech:event', (_event, event) => callback(event)),
  dragMove: () => ipcRenderer.send('pet:drag-move'),
  dragStart: () => ipcRenderer.send('pet:drag-start'),
  dragEnd: () => ipcRenderer.send('pet:drag-end'),
  ignoreMouse: (ignore) => ipcRenderer.send('pet:mouse-ignore', ignore),
  openChat: () => ipcRenderer.send('pet:open-chat'),
  openSettings: () => ipcRenderer.send('pet:open-settings'),
  quit: () => ipcRenderer.send('pet:quit'),
  contextMenu: () => ipcRenderer.send('pet:context-menu'),
  onRename: (callback) => ipcRenderer.on('pet:renamed', (_event, name) => callback(name)),
  onChatMode: (callback) => ipcRenderer.on('chat:mode', (_event, mode) => callback(mode)),
  onChatActivity: (callback) => ipcRenderer.on('chat:activity', (_event, state) => callback(state)),
  onSpeechTurn: (callback) => ipcRenderer.on('chat:speech-turn', (_event, turn) => callback(turn)),
  onState: (callback) => ipcRenderer.on('pet:state', (_event, state) => callback(state)),
  onAction: (callback) => ipcRenderer.on('pet:action', (_event, id) => callback(id)),
  onExpression: (callback) => ipcRenderer.on('pet:expression', (_event, id) => callback(id)),
  onVoice: (callback) => ipcRenderer.on('pet:voice', (_event, clip) => callback(clip)),
  onVoiceStop: (callback) => ipcRenderer.on('pet:voice-stop', () => callback()),
  onVoiceStatus: (callback) => ipcRenderer.on('pet:voice-status', (_event, value) => callback(value)),
  onPreferences: (callback) => ipcRenderer.on('pet:preferences', (_event, value) => callback(value)),
  onNotice: (callback) => ipcRenderer.on('pet:notice', (_event, value) => callback(value)),
  onSticker: (callback) => ipcRenderer.on('pet:sticker', (_event, value) => callback(value)),
  onHideSticker: (callback) => ipcRenderer.on('pet:sticker-hide', () => callback()),
  onChatReply: (callback) => ipcRenderer.on('pet:chat-reply', (_event, reply) => callback(reply)),
});
